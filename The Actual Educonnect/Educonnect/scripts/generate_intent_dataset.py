def main():
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data_dir = os.path.join(base, "data")
    os.makedirs(data_dir, exist_ok=True)
    out_path = os.path.join(data_dir, "intents.csv")

    rows = []
    for label, messages in INTENT_TEMPLATES.items():
        for msg in messages:
            rows.append({"message": msg, "label": label})

    random.seed(42)
    random.shuffle(rows)

    with open(out_path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["message", "label"])
        w.writeheader()
        w.writerows(rows)

    print(f"Wrote {len(rows)} rows to {out_path}")
    for label in INTENT_TEMPLATES:
        n = sum(1 for r in rows if r["label"] == label)
        print(f"  {label}: {n} examples")

if __name__ == "__main__":
    main()
